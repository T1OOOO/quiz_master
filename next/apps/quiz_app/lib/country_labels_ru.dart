/// Returns a reviewed Russian label for shipped country-atlas values.
/// Unknown synthetic fixture values are intentionally returned unchanged.
String russianCountryLabel(String value) {
  final direct = russianCountryLabels[value];
  if (direct != null) return direct;
  if (!value.contains(',') && !value.contains(';')) return value;
  return value.splitMapJoin(
    RegExp(r'([,;])'),
    onMatch: (match) => match[0]!,
    onNonMatch: (part) {
      final leading = RegExp(r'^\s*').firstMatch(part)![0]!;
      final trailing = RegExp(r'\s*$').firstMatch(part)![0]!;
      final key = part.trim();
      return "$leading${russianCountryLabels[key] ?? key}$trailing";
    },
  );
}
